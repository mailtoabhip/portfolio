import * as THREE from "three";

/**
 * Curved-world turns.
 *
 * The truck never really turns: the world still slides toward the
 * camera along +Z (see Forest.tsx). Turns are a vertex-shader bend:
 * every vertex ahead of the cab is pushed sideways by
 * `uBend * distance²`, so the road, trees, divider and ground all
 * curve away together. Changing `uBend` over distance (driven by
 * `advanceCurve`) makes gentle left/right bends approach, sweep past
 * and straighten out — the classic endless-runner trick, with no
 * change to the recycling or collision logic.
 */

export const curveUniform = { value: 0 };

/** Vertices closer than this (the cab, the dash props) never bend. */
const BEND_START = 2.0;
/** Beyond this the offset stops growing, so the horizon can't swing. */
const BEND_MAX_DIST = 240.0;

const PATCH_KEY = "cw1";

function patchShader(shader: THREE.WebGLProgramParametersWithUniforms) {
  if (!shader.vertexShader.includes("#include <project_vertex>")) return;
  shader.uniforms.uBend = curveUniform;
  shader.vertexShader =
    "uniform float uBend;\n" +
    shader.vertexShader.replace(
      "#include <project_vertex>",
      /* glsl */ `
      vec4 mvPosition = vec4( transformed, 1.0 );
      #ifdef USE_BATCHING
        mvPosition = batchingMatrix * mvPosition;
      #endif
      #ifdef USE_INSTANCING
        mvPosition = instanceMatrix * mvPosition;
      #endif
      vec4 cwWorld = modelMatrix * mvPosition;
      float cwD = clamp( -cwWorld.z - ${BEND_START.toFixed(1)}, 0.0, ${BEND_MAX_DIST.toFixed(1)} );
      cwWorld.x += uBend * cwD * cwD;
      mvPosition = viewMatrix * cwWorld;
      gl_Position = projectionMatrix * mvPosition;
      `
    );
}

/** Adds the bend to a material, keeping any onBeforeCompile it already has. */
export function bendMaterial(mat: THREE.Material) {
  const ud = mat.userData as { cwPatched?: boolean };
  if (ud.cwPatched || mat instanceof THREE.ShaderMaterial) return;
  ud.cwPatched = true;
  const prevCompile = mat.onBeforeCompile.bind(mat);
  const prevKey = mat.customProgramCacheKey.bind(mat);
  mat.onBeforeCompile = (shader, renderer) => {
    prevCompile(shader, renderer);
    patchShader(shader);
  };
  mat.customProgramCacheKey = () => prevKey() + PATCH_KEY;
  mat.needsUpdate = true;
}

/** Walks a scene and bends every mesh material not opted out via
 * `userData.noBend` (sky dome, far hills, clouds, the sun disc). */
export function bendScene(root: THREE.Object3D) {
  root.traverse((o) => {
    if ((o.userData as { noBend?: boolean }).noBend) return;
    const mesh = o as THREE.Mesh;
    if (!mesh.isMesh && !(o as THREE.Points).isPoints) return;
    const m = mesh.material;
    if (Array.isArray(m)) m.forEach(bendMaterial);
    else if (m) bendMaterial(m);
  });
}

// ---- The route: straights and gentle bends, generated by distance ----

type Leg = { len: number; bend: number };

function randomLeg(prevBend: number): Leg {
  if (prevBend !== 0 || Math.random() < 0.35) {
    // straight
    return { len: 220 + Math.random() * 260, bend: 0 };
  }
  const dir = Math.random() < 0.5 ? -1 : 1;
  // ~0.0007–0.0014: soft highway curves, never hairpins.
  return { len: 260 + Math.random() * 240, bend: dir * (0.0007 + Math.random() * 0.0007) };
}

const route = {
  leg: { len: 260, bend: 0 } as Leg, // start on a straight
  left: 260,
  current: 0,
};

/** Call every frame with metres travelled; updates `curveUniform`. */
export function advanceCurve(dz: number) {
  route.left -= dz;
  if (route.left <= 0) {
    route.leg = randomLeg(route.leg.bend);
    route.left = route.leg.len;
  }
  // Ease toward the leg's bend over ~120 m so curves roll in and out.
  const k = Math.min(1, dz / 120);
  route.current += (route.leg.bend - route.current) * k;
  curveUniform.value = route.current;
}
